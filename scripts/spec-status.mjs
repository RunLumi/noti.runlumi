#!/usr/bin/env node
/**
 * Spec status ledger generator.
 *
 * Parses every `docs/specs/NN-*.md` feature entry (`## Fnn - Title` followed by a
 * `**Priority** Pn ... **Status** <glyph> <note>` line) and renders `docs/specs/STATUS.md`:
 * a table of every feature plus per-spec and overall counts. The spec files are the source of
 * truth; STATUS.md is derived and must never be edited by hand.
 *
 *   npm run docs:spec-status            rewrite docs/specs/STATUS.md
 *   node scripts/spec-status.mjs --check  exit 1 if STATUS.md is stale (CI / pre-merge)
 *
 * Plain ESM with no dependencies so it runs without a build step (like scripts/audit-gate.mjs).
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const SPEC_DIR = join(root, 'docs', 'specs');
export const STATUS_FILE = join(SPEC_DIR, 'STATUS.md');
export const README_FILE = join(SPEC_DIR, 'README.md');
export const README_BEGIN = '<!-- spec-status:begin (generated by scripts/spec-status.mjs; do not edit) -->';
export const README_END = '<!-- spec-status:end -->';

/** Glyph -> label, in the order the tables list them. */
export const GLYPHS = [
  ['✅', 'Done'],
  ['🟡', 'Partial'],
  ['❌', 'Not started'],
  ['⛔', 'Blocked'],
  ['🚫', 'Deferred / decided against'],
];

const FEATURE_HEADING = /^#{2,4}\s+(F\d{2,3})\s+[—–-]\s+(.+?)\s*$/;
const PRIORITY_LINE = /^\*\*Priority\*\*\s+(P[012])\b.*?\*\*Status\*\*\s*(.*)$/;
const SPEC_FILE = /^\d\d-.*\.md$/;
/** Evidence: a path-like code span, or a PR / ADR reference. */
const EVIDENCE = /`[^`\s]*[./][^`\s]*`|\bPR #\d+|\bADR \d{4}/;

export function listSpecFiles(dir = SPEC_DIR) {
  return readdirSync(dir)
    .filter((f) => SPEC_FILE.test(f))
    .sort();
}

/**
 * Parse one spec's markdown into features. Throws on a feature without a Priority/Status line,
 * because a silent skip is exactly how the catalogue went stale.
 */
export function parseSpec(file, text) {
  const features = [];
  const lines = text.split('\n');
  let current = null;
  for (const line of lines) {
    const heading = FEATURE_HEADING.exec(line);
    if (heading) {
      if (current && !current.priority) throw new Error(`${file}: ${current.id} has no Priority line`);
      current = { id: heading[1], title: heading[2], file, priority: '', status: '', glyph: '', note: '' };
      features.push(current);
      continue;
    }
    if (!current || current.priority) continue;
    const m = PRIORITY_LINE.exec(line);
    if (!m) continue;
    current.priority = m[1];
    // The status text ends at the next bold field (` · **Fixes** ...`) or the end of the line.
    const raw = m[2];
    const cut = raw.indexOf(' · **');
    current.status = (cut >= 0 ? raw.slice(0, cut) : raw).trim();
    const glyph = GLYPHS.map(([g]) => g).find((g) => current.status.startsWith(g)) ?? '';
    current.glyph = glyph;
    current.note = current.status.slice(glyph.length).trim();
  }
  if (current && !current.priority) throw new Error(`${file}: ${current.id} has no Priority line`);
  return features;
}

export function parseSpecs(dir = SPEC_DIR) {
  return listSpecFiles(dir).flatMap((f) => parseSpec(f, readFileSync(join(dir, f), 'utf8')));
}

export function hasEvidence(note) {
  return EVIDENCE.test(note);
}

const emptyCounts = () => Object.fromEntries(GLYPHS.map(([g]) => [g, 0]));

export function countBy(features, keyFn) {
  const out = new Map();
  for (const f of features) {
    const key = keyFn(f);
    if (!out.has(key)) out.set(key, emptyCounts());
    const c = out.get(key);
    if (f.glyph in c) c[f.glyph] += 1;
  }
  return out;
}

function total(counts) {
  return Object.values(counts).reduce((a, b) => a + b, 0);
}

function cell(text, max) {
  const flat = text.replace(/\s+/g, ' ').replace(/\|/g, '\\|');
  if (flat.length <= max) return flat;
  // Cut at a word boundary and never inside a backtick span, so the table keeps valid code spans.
  let cutAt = flat.lastIndexOf(' ', max);
  if (cutAt < 40) cutAt = max;
  let clipped = flat.slice(0, cutAt).trimEnd();
  if ((clipped.match(/`/g) ?? []).length % 2 === 1)
    clipped = clipped.slice(0, clipped.lastIndexOf('`')).trimEnd();
  return `${clipped} …`;
}

function countRow(label, counts) {
  return `| ${label} | ${GLYPHS.map(([g]) => counts[g]).join(' | ')} | ${total(counts)} |`;
}

export function overallCounts(features) {
  return countBy(features, () => 'all').get('all') ?? emptyCounts();
}

export function renderStatus(features) {
  const header = ['Status', ...GLYPHS.map(([g, l]) => `${g} ${l}`), 'Total'];
  const sep = header.map(() => '---');
  const out = [];
  out.push('# Spec status ledger');
  out.push('');
  out.push('> **Generated by `npm run docs:spec-status` from the `**Priority**` / `**Status**` lines in');
  out.push("> `docs/specs/NN-*.md`. Do not edit by hand.** Change a feature's status in its spec file and");
  out.push('> regenerate. `tests/spec-status.test.ts` fails if this file is stale, if any of F01 to F262');
  out.push('> is missing or duplicated, or if a P0 feature is marked ✅ without an evidence pointer.');
  out.push('>');
  out.push(
    '> ✅ implemented and covered by tests · 🟡 partly (the note says what is missing) · ❌ not started ·',
  );
  out.push(
    '> ⛔ blocked (the note says by what) · 🚫 deferred or decided against (the note cites the reason).',
  );
  out.push('> "Done" means merged with tests. It does not mean production-ready: see');
  out.push('> [`../RELEASE_GATES.md`](../RELEASE_GATES.md).');
  out.push('');
  out.push('## Overall');
  out.push('');
  out.push(`| ${header.join(' | ')} |`);
  out.push(`| ${sep.join(' | ')} |`);
  out.push(countRow('All features', overallCounts(features)));
  const byPriority = countBy(features, (f) => f.priority);
  for (const p of ['P0', 'P1', 'P2']) if (byPriority.has(p)) out.push(countRow(p, byPriority.get(p)));
  out.push('');
  out.push('## Per spec');
  out.push('');
  out.push(`| ${['Spec', ...header.slice(1)].join(' | ')} |`);
  out.push(`| ${sep.join(' | ')} |`);
  const bySpec = countBy(features, (f) => f.file);
  for (const [file, counts] of bySpec) out.push(countRow(`[${file}](${file})`, counts));
  out.push('');
  out.push('## Features');
  out.push('');
  out.push('| ID | Title | Spec | Pri | | Note |');
  out.push('| --- | --- | --- | --- | --- | --- |');
  for (const f of features) {
    const spec = f.file.slice(0, 2);
    out.push(
      `| ${f.id} | ${cell(f.title, 70)} | [${spec}](${f.file}) | ${f.priority} | ${f.glyph || '?'} | ${cell(f.note, 230)} |`,
    );
  }
  out.push('');
  return out.join('\n');
}

/** The generated block embedded in README.md: overall counts only, linking to the full ledger. */
export function renderReadmeBlock(features) {
  const c = overallCounts(features);
  const byPriority = countBy(features, (f) => f.priority);
  const rows = ['P0', 'P1', 'P2']
    .filter((p) => byPriority.has(p))
    .map(
      (p) =>
        `| ${p} | ${GLYPHS.map(([g]) => byPriority.get(p)[g]).join(' | ')} | ${total(byPriority.get(p))} |`,
    );
  return [
    README_BEGIN,
    `| | ${GLYPHS.map(([g, l]) => `${g} ${l}`).join(' | ')} | Total |`,
    `| --- | ${GLYPHS.map(() => '---').join(' | ')} | --- |`,
    `| **All features** | ${GLYPHS.map(([g]) => c[g]).join(' | ')} | ${total(c)} |`,
    ...rows,
    README_END,
  ].join('\n');
}

/** Replace the marked block in README text; throws when the markers are missing. */
export function applyReadmeBlock(readme, features) {
  const start = readme.indexOf(README_BEGIN);
  const end = readme.indexOf(README_END);
  if (start < 0 || end < start) throw new Error('docs/specs/README.md is missing the spec-status markers');
  return readme.slice(0, start) + renderReadmeBlock(features) + readme.slice(end + README_END.length);
}

export function generate(dir = SPEC_DIR) {
  return renderStatus(parseSpecs(dir));
}

function main() {
  const features = parseSpecs();
  const text = renderStatus(features);
  const readme = applyReadmeBlock(readFileSync(README_FILE, 'utf8'), features);
  if (process.argv.includes('--check')) {
    const read = (f) => {
      try {
        return readFileSync(f, 'utf8');
      } catch {
        return ''; // a missing file counts as stale
      }
    };
    if (read(STATUS_FILE) !== text || read(README_FILE) !== readme) {
      console.error('docs/specs/STATUS.md or the README counts are stale. Run `npm run docs:spec-status`.');
      process.exit(1);
    }
    console.log('docs/specs/STATUS.md and README counts are up to date.');
    return;
  }
  writeFileSync(STATUS_FILE, text);
  writeFileSync(README_FILE, readme);
  const c = overallCounts(features);
  console.log(
    `wrote docs/specs/STATUS.md and README counts: ${GLYPHS.map(([g]) => `${g} ${c[g]}`).join('  ')}  total ${total(c)}`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
