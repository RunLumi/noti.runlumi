/**
 * Renders `docs/CAPABILITIES.md` from the destination kind registry (F120, ADR 0052). Pure and
 * deterministic: no clock, no environment, no file access. `npm run docs:capabilities` writes
 * the file; `tests/destinations/kind-registry.test.ts` fails when the committed copy differs.
 */
import {
  DESTINATION_FEATURES,
  DESTINATION_KINDS,
  DESTINATION_REGISTRY,
  NOT_OFFERED,
  type DestinationLimit,
  type DestinationRegistration,
  type LimitBasis,
  type ReferenceSource,
} from './kind-registry';
import type { DestinationCapabilities, SigningScheme } from './types';

const REFERENCE = 'DESTINATION_API_REFERENCE.md';

const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

/** `40000` → `40,000`, without depending on the runtime's locale data. */
export function groupDigits(n: number): string {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
}

const yesNo = (v: boolean): string => (v ? 'Yes' : 'No');

const SIGNING: Readonly<Record<SigningScheme, string>> = {
  none: 'No',
  lark_hmac_sha256: 'Yes, Lark HMAC-SHA256 (with the secret from Lark)',
  standard_webhooks_v1: 'Yes, Standard Webhooks v1 (secret generated by Noti, shown once)',
};

const BASIS: Readonly<Record<LimitBasis, string>> = {
  provider: 'Provider',
  derived: 'Derived from a provider limit',
  ours: 'Noti budget',
  not_stated: '⚠️ Not stated in the reference',
};

function cite(source: ReferenceSource): string {
  return `[${REFERENCE} §${source.section}](${REFERENCE}): “${cell(source.excerpt)}”`;
}

function availability(r: DestinationRegistration): string {
  return r.availability.gate === 'none'
    ? 'Offered'
    : `Off unless \`${r.availability.variable}=true\` (deployment flag)`;
}

interface MatrixRow {
  readonly label: string;
  readonly value: (r: DestinationRegistration, c: DestinationCapabilities) => string;
}

const MATRIX: readonly MatrixRow[] = [
  { label: 'Mode', value: (_r, c) => `\`${c.mode}\`` },
  { label: 'Availability', value: (r) => availability(r) },
  { label: 'Message formats, richest first', value: (_r, c) => c.formats.join(', ') },
  {
    label: 'What a success means',
    value: (r) =>
      r.confirmation.source
        ? `${r.confirmation.text} (§${r.confirmation.source.section})`
        : r.confirmation.text,
  },
  { label: 'Request signed', value: (_r, c) => SIGNING[c.signing] },
  { label: 'Links back to the source', value: (_r, c) => yesNo(c.supportsLinks) },
  {
    label: '@mentions',
    value: (_r, c) => (c.supportsMentions ? 'Yes' : 'No: untrusted text never pings anyone'),
  },
  { label: 'Update a sent message', value: (_r, c) => yesNo(c.canUpdate) },
  { label: 'Delete a sent message', value: (_r, c) => yesNo(c.canDelete) },
  { label: 'Reply in a thread', value: (_r, c) => yesNo(c.canReply) },
  { label: 'Interactive buttons', value: (_r, c) => yesNo(c.supportsInteractive) },
  { label: 'Custom sender name or icon', value: (_r, c) => yesNo(c.canCustomizeIdentity) },
  {
    label: 'Server-side deduplication',
    value: (_r, c) => (c.supportsServerSideIdempotency ? 'Yes' : 'No: a retry can appear twice'),
  },
  { label: 'Phone numbers and emails masked', value: (_r, c) => yesNo(c.redactsContactDetails) },
  { label: 'Body budget', value: (_r, c) => `${groupDigits(c.maxBodyBytes)} bytes` },
  { label: 'Title limit', value: (_r, c) => `${groupDigits(c.maxTitleChars)} characters` },
  { label: 'Text limit', value: (_r, c) => `${groupDigits(c.maxTextChars)} characters` },
  {
    label: 'Credential',
    value: (_r, c) =>
      c.requiresCustomerOwnedCredential
        ? 'A URL the customer supplies, stored encrypted and never shown again'
        : 'Managed by Noti',
  },
];

function formatValue(limit: DestinationLimit): string {
  if (typeof limit.value === 'string') return limit.value;
  return limit.unit === 'items' ? groupDigits(limit.value) : `${groupDigits(limit.value)} ${limit.unit}`;
}

function limitsTable(r: DestinationRegistration): string[] {
  const lines = ['| Limit | Value | Basis | Source | Note |', '| --- | --- | --- | --- | --- |'];
  for (const limit of r.limits) {
    const needsSource = limit.basis === 'provider' || limit.basis === 'derived';
    // F120: a provider fact without a citation is not printed.
    if (needsSource && !limit.source)
      throw new Error(`${r.kind}.${limit.id}: a ${limit.basis} limit needs a source`);
    if (!needsSource && limit.source)
      throw new Error(`${r.kind}.${limit.id}: a ${limit.basis} limit must not cite the reference`);
    const enforced = limit.enforcedAs ? ` Enforced as \`${limit.enforcedAs}\`.` : '';
    lines.push(
      `| ${cell(limit.label)} | ${cell(formatValue(limit))} | ${BASIS[limit.basis]} | ${
        limit.source ? cite(limit.source) : 'not stated'
      } | ${cell((limit.note ?? '') + enforced).trim()} |`,
    );
  }
  return lines;
}

export function renderCapabilitiesDoc(): string {
  const regs = DESTINATION_KINDS.map((k) => DESTINATION_REGISTRY[k] as DestinationRegistration);
  const out: string[] = [
    '# Destination capabilities',
    '',
    '<!-- Generated by `npm run docs:capabilities` from src/connectors/destinations/kind-registry.ts. Do not edit by hand. -->',
    '',
    'What each destination can do in Noti today, generated from the destination registry (spec 09 F105 and',
    'F120, ADR 0052). It describes what Noti’s adapter for each mode does, not everything the provider',
    'could do: Discord can edit a message, for example, but Noti does not keep message ids yet, so it says',
    'No. Provider facts cite the section of [`DESTINATION_API_REFERENCE.md`](DESTINATION_API_REFERENCE.md)',
    'they come from (researched 2026-10-13). Where that reference does not state a value, this page says so.',
    '',
    'This page is documentation, not acceptance evidence: nothing on it shows that a real provider account',
    'accepted a Noti message.',
    '',
    '## Capability matrix',
    '',
    `| | ${regs.map((r) => r.label).join(' | ')} |`,
    `| --- | ${regs.map(() => '---').join(' | ')} |`,
    ...MATRIX.map(
      (row) => `| ${row.label} | ${regs.map((r) => cell(row.value(r, r.capabilities))).join(' | ')} |`,
    ),
    '',
    'The adapters read these values from the registry at render time, and `tests/destinations/conformance.test.ts`',
    'pins them in a golden table. When a message is too large for one format, Noti tries the next in the list.',
    'An over-long field is shortened visibly with an ellipsis; a message that fits no format fails as',
    '`payload_too_large` rather than being cut off silently.',
    '',
    '## Limits and where they come from',
    '',
    '“Noti budget” is a limit Noti sets where the provider has none. “Not stated” means Noti enforces a value',
    'the reference does not give; it is listed so it can be checked, not hidden.',
    '',
  ];
  for (const r of regs) {
    out.push(`### ${r.label}`, '', ...limitsTable(r), '');
  }
  out.push('## What is not known', '');
  const open = regs.flatMap((r) => r.openQuestions.map((q) => ({ r, q })));
  for (const { r, q } of open) out.push(`- **${r.label}.** ${q.text} ${cite(q.source)}`);
  out.push(
    '',
    '## Features checked when a destination is saved',
    '',
    'The integrations API refuses a requested `format` or `features` entry that the destination cannot',
    'provide, with the reason, instead of storing it and silently doing less at delivery (spec 07 F93).',
    'Only the default (richest) format can be named today, because no stored setting holds a format choice.',
    '',
    `| Feature (\`features\` value) | ${regs.map((r) => r.label).join(' | ')} |`,
    `| --- | ${regs.map(() => '---').join(' | ')} |`,
  );
  for (const [id, feature] of Object.entries(DESTINATION_FEATURES)) {
    out.push(
      `| ${feature.label} (\`${id}\`) | ${regs
        .map((r) =>
          r.capabilities[feature.capability] === true
            ? 'Refused: not selectable yet'
            : 'Refused: not supported',
        )
        .join(' | ')} |`,
    );
  }
  out.push('', '## Not offered', '');
  for (const item of NOT_OFFERED) out.push(`- **${item.name}.** ${item.reason} ${cite(item.source)}`);
  out.push('');
  return out.join('\n');
}
