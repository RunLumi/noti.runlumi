/**
 * Renders the retention matrix as `docs/DATA_RETENTION.md`. Pure and deterministic: no clock,
 * no environment. `npm run docs:retention` writes the file; a test fails when the committed
 * copy differs from this output.
 */
import {
  LEDGER_TABLES_OUTLIVING_PURGE,
  NOT_STORED,
  OPERATOR_TO_DECIDE,
  PLATFORM_STORES,
  RETENTION_MATRIX,
  type Deletion,
  type Retention,
  type RetentionRow,
} from './retention';

const MINUTE = 60_000;
const HOUR = 60 * MINUTE;
const DAY = 24 * HOUR;

export function humanDuration(ms: number): string {
  if (ms % DAY === 0) return ms === DAY ? '1 day' : `${String(ms / DAY)} days`;
  if (ms % HOUR === 0) return ms === HOUR ? '1 hour' : `${String(ms / HOUR)} hours`;
  if (ms % MINUTE === 0) return `${String(ms / MINUTE)} minutes`;
  return `${String(Math.round(ms / 1000))} seconds`;
}

export function describeRetention(r: Retention): string {
  switch (r.kind) {
    case 'fixed':
      return `${humanDuration(r.ms)} (${r.basis})${r.note ? `. ${r.note}` : ''}`;
    case 'configurable':
      return `${r.variable}: default ${humanDuration(r.defaultMs)}, allowed ${humanDuration(r.minMs)} to ${humanDuration(r.maxMs)}`;
    case 'while_parent_exists':
      return r.parent === 'account'
        ? 'Until the account is deleted'
        : `While the workspace exists; ${r.graceMs ? humanDuration(r.graceMs) : 'no'} grace period after a deletion request`;
    case 'until_expiry':
      return `${r.expiryMs === null ? 'Until the record expires (its own expiry)' : `Until it expires (${humanDuration(r.expiryMs)})`}${
        r.afterExpiryMs > 0
          ? `, then ${humanDuration(r.afterExpiryMs)} more`
          : ', then removed at the next hourly pass'
      }`;
    case 'indefinite':
      return `No expiry. ${r.reason}`;
    case 'temporary':
      return `TEMPORARY. ${r.dropBy}`;
    case 'not_enforced':
      return `NOT ENFORCED. ${r.gap}`;
  }
}

export function describeDeletion(d: Deletion): string {
  switch (d.kind) {
    case 'cron_job':
      return `cron job \`${d.job}\``;
    case 'workspace_purge':
      return `workspace purge (${d.route.replaceAll('_', ' ')})`;
    case 'fk_cascade':
      return `foreign-key cascade from \`${d.parent}\``;
    case 'account_erasure':
      return 'account erasure (`DELETE /api/workspace/me`)';
    case 'customer_delete':
      return `customer deletes the ${d.object}`;
    case 'none':
      return `none. ${d.reason}`;
  }
}

const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

function exportCell(row: RetentionRow): string {
  const where = [row.inWorkspaceExport ? 'workspace' : null, row.inAccountExport ? 'account' : null].filter(
    (x): x is string => x !== null,
  );
  const base = where.length > 0 ? where.join(' and ') : 'neither';
  return row.exportNote ? `${base}. ${row.exportNote}` : base;
}

function storeName(row: RetentionRow): string {
  return row.columns
    ? `\`${row.table}\` (${row.columns.length} columns: ${row.id.endsWith('credentials') ? 'sealed credentials' : 'configuration'})`
    : `\`${row.table}\``;
}

function matrixTable(): string[] {
  const lines = [
    '| Store | Data held | Purpose | Category | Personal data | Retention | Removed by | Exported in |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const row of RETENTION_MATRIX) {
    lines.push(
      `| ${[
        storeName(row),
        row.dataHeld,
        row.purpose,
        `\`${row.category}\``,
        row.personalData,
        describeRetention(row.retention),
        row.deletion.map(describeDeletion).join('; '),
        exportCell(row),
      ]
        .map(cell)
        .join(' | ')} |`,
    );
  }
  return lines;
}

export function renderRetentionDoc(): string {
  const gaps = RETENTION_MATRIX.filter((r) => r.retention.kind === 'not_enforced');
  const notes = RETENTION_MATRIX.filter((r) => r.notes);
  const out: string[] = [
    '# Data retention matrix',
    '',
    '<!-- Generated by `npm run docs:retention` from src/compliance/retention.ts. Do not edit by hand:',
    '     tests/compliance/retention.test.ts fails when this file differs from the generator output. -->',
    '',
    'This is the engineering record of what Lumi Noti stores, why, for how long and how it is removed',
    '(spec 15 F237). Every period below is read from the code that enforces it. **It is not a privacy',
    'policy and contains no legal conclusion.** Legal basis, controller or processor role, and any',
    `regulatory retention period are ${OPERATOR_TO_DECIDE}. No formal security audit has been performed.`,
    '',
    'A test lists every table created by the migrations and fails if one is missing from the matrix, so a',
    'new table cannot ship without a retention decision. It also checks that each removal mechanism named',
    'below exists in the schema or the purge code.',
    '',
    '## D1 stores',
    '',
    ...matrixTable(),
    '',
    '## Legal basis (to be completed by the operator)',
    '',
    `Every row has a \`legalBasis\` and a \`controllerRole\` field in \`src/compliance/retention.ts\`, set to "${OPERATOR_TO_DECIDE}".`,
    'This repository takes no position on them. The operator must decide, per row, why the data may be',
    'processed and in which role, and record it with qualified advice before the documents are shown to',
    'customers.',
    '',
    '| Store | Legal basis | Controller or processor role |',
    '| --- | --- | --- |',
    ...RETENTION_MATRIX.map((r) => `| ${cell(storeName(r))} | ${r.legalBasis} | ${r.controllerRole} |`),
    '',
    '## Stores outside D1',
    '',
    'Not machine-checked. The retention of these is set by Cloudflare or by account configuration, not by this code.',
    '',
    '| Store | Holds | Retention | Enforced by |',
    '| --- | --- | --- | --- |',
    ...PLATFORM_STORES.map(
      (s) => `| ${cell(s.store)} | ${cell(s.holds)} | ${cell(s.retention)} | ${cell(s.enforcedBy)} |`,
    ),
    '',
    '## Not stored (spec rows that do not apply)',
    '',
    'The spec retention table (docs/specs/15 F237) names these. The code does not store them, so no period applies.',
    '',
    '| Spec row | Decision |',
    '| --- | --- |',
    ...NOT_STORED.map((n) => `| ${cell(n.spec)} | ${cell(n.reason)} |`),
    '',
    '## Deletion and its limits',
    '',
    '- **Workspace deletion** is two-phase: integrations are disabled at once, and a cron purge removes every',
    '  tenant row and the workspace after the grace period shown above (`src/pipeline/purge.ts`). Deleting an',
    '  integration or source row destroys its wrapped data key, so sealed credentials cannot be opened afterwards.',
    '- **Account erasure** (`DELETE /api/workspace/me`) deletes the person and everything that cascades from them.',
    '  It refuses (409) while the person is the only admin of a workspace. See `docs/DSAR.md`.',
    '- **Not erasure:** D1 Time Travel keeps point-in-time history for a period set by Cloudflare, so a deleted row',
    '  can still exist in that history until the window passes (AR-6). Queues and logs are likewise Cloudflare-retained.',
    `- Tables that carry an \`organization_id\` but are deliberately not removed by the workspace purge: ${LEDGER_TABLES_OUTLIVING_PURGE.map((t) => `\`${t}\``).join(', ')}.`,
    '',
    '## Known gaps',
    '',
    ...(gaps.length > 0
      ? gaps.map(
          (r) =>
            `- \`${r.table}\`: ${typeof r.retention === 'object' && r.retention.kind === 'not_enforced' ? r.retention.gap : ''}`,
        )
      : ['- None recorded.']),
    '- The expiry-based purge (`expired_auth_purge`) runs once an hour. `github_auth_states` has an index on its expiry (migration 0010);',
    '  `session`, `verification` and `rate_limit` do not, so those scans read the whole table. Acceptable at current volume; add an index if they grow.',
    '  A sanity guard aborts the pass, and logs `expired_purge_aborted`, if an expiry looks like seconds instead of milliseconds or more than half of a large `session` table would go.',
    '- Accounts whose email was never verified are not purged by any job, and they cannot use `DELETE /api/workspace/me` (it needs a verified session). Only an operator can remove them (`RUNBOOK.md`, "Data-subject requests").',
    '- Audit rows are append-only and keep the actor id, IP address and user agent after the actor is erased, until the audit retention.',
    '- The workspace export does not include notification content (`notification_outbox`, `held_events`) or repository lists.',
    '',
    '## Notes per store',
    '',
    ...notes.map((r) => `- \`${r.table}\`${r.columns ? ` (${r.id})` : ''}: ${r.notes ?? ''}`),
    '',
  ];
  return out.join('\n');
}
